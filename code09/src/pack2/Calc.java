package pack2;

public class Calc {

    //return-type name
    public static int sum(int a, int b) {
        return a + b;
    }

    public static int sum(int a, int b, int c) {
        return a + b + c;
    }

    public static int sum(double a, double b) {
        return ((int) (a + b));
    }
}
